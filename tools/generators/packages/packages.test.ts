import { expect, test } from 'bun:test';

import type { Tree } from '@nx/devkit';
import { createTreeWithEmptyWorkspace } from '@nx/devkit/testing';
import { packagesGenerator } from '@tools/generators/packages/generator.ts';

/** A tree with two packages, the sync engine, a web app, a native app, a server app and the command-line app. */
function workspace(): Tree {
  const tree = createTreeWithEmptyWorkspace();
  tree.write('packages/notes/runtime/client.ts', 'export const notesClient = {};\n');
  tree.write('packages/notes/runtime/server.server.ts', 'export const notesServer = {};\n');
  tree.write('packages/access/runtime/client.ts', 'export const accessClient = {};\n');
  tree.write('packages/access/runtime/server.server.ts', 'export const accessServer = {};\n');
  // The sync engine has a server half of its own, but it holds no contract.
  tree.write('packages/sync/runtime/server.server.ts', 'export const syncServer = {};\n');
  tree.write('packages/notes/types/note.ts', 'export type Note = {};\n');
  tree.write(
    'apps/web/package.json',
    JSON.stringify({ name: 'web', dependencies: { react: '19.3.1' } }),
  );
  tree.write('apps/web/src/main.tsx', '');
  tree.write(
    'apps/mobile/package.json',
    JSON.stringify({ name: 'mobile', dependencies: { expo: '55.0.0' } }),
  );
  tree.write('apps/mobile/lib/app.tsx', '');
  tree.write(
    'apps/api/package.json',
    JSON.stringify({ name: 'api', nx: { tags: ['platform:server'] } }),
  );
  tree.write('apps/api/src/server.ts', '');
  tree.write('apps/cli/package.json', JSON.stringify({ name: '@repo/cli', dependencies: {} }));
  tree.write('apps/cli/src/main.ts', '');
  return tree;
}

test('the sync writes the client list of each client app and the server list of each server app, sorted by package', () => {
  const tree = workspace();
  expect(packagesGenerator(tree)).toMatchObject({
    outOfSyncMessage: expect.stringContaining('apps/web/src/packages.ts'),
  });
  expect(tree.read('apps/web/src/packages.ts', 'utf-8')).toBe(
    [
      '// Generated by `nx sync` from the packages that have `runtime/client.ts` or `runtime/server.server.ts`. Do not edit it.',
      "import { accessClient } from '@repo/access/runtime/client';",
      "import { notesClient } from '@repo/notes/runtime/client';",
      '',
      'export const packages = [accessClient, notesClient];',
      '',
    ].join('\n'),
  );
  expect(tree.read('apps/api/src/packages.ts', 'utf-8')).toBe(
    [
      '// Generated by `nx sync` from the packages that have `runtime/client.ts` or `runtime/server.server.ts`. Do not edit it.',
      "import { accessServer } from '@repo/access/runtime/server.server';",
      "import { notesServer } from '@repo/notes/runtime/server.server';",
      '',
      'export const packages = [accessServer, notesServer];',
      '',
    ].join('\n'),
  );
});

test('a native app keeps its list in lib/, and the sync engine is not a package of the list', () => {
  const tree = workspace();
  packagesGenerator(tree);
  expect(tree.read('apps/mobile/lib/packages.ts', 'utf-8')).toContain(
    'export const packages = [accessClient, notesClient];',
  );
  expect(tree.exists('apps/mobile/src/packages.ts')).toBe(false);
  expect(tree.read('apps/api/src/packages.ts', 'utf-8')).not.toContain('syncServer');
});

test('the sync writes nothing when each list is current, and leaves the command-line app alone', () => {
  const tree = workspace();
  packagesGenerator(tree);
  expect(packagesGenerator(tree)).toEqual({});
  expect(tree.exists('apps/cli/src/packages.ts')).toBe(false);
});

test('a package that gains its client half changes the lists of the client apps only', () => {
  const tree = workspace();
  packagesGenerator(tree);
  tree.write('packages/billing/runtime/client.ts', 'export const billingClient = {};\n');
  expect(packagesGenerator(tree)).toMatchObject({
    outOfSyncMessage: expect.stringContaining('apps/web/src/packages.ts'),
  });
  expect(tree.read('apps/web/src/packages.ts', 'utf-8')).toContain(
    "import { billingClient } from '@repo/billing/runtime/client';",
  );
  expect(tree.read('apps/api/src/packages.ts', 'utf-8')).not.toContain('billing');
});
