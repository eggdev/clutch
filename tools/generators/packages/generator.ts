import type { Tree } from '@nx/devkit';
import { names, readJson } from '@nx/devkit';
import { isClientApp, isServerApp } from '@tools/apps';
import type { Manifest } from '@tools/apps';

/**
 * The sync generator of the app lists. Each client app lists the client half of
 * every package, and each server app lists the server half. `nx sync` writes
 * the list, so an app never lists a package by hand. See
 * docs/contributing/architecture/contract.md.
 */

/** The side of an app: the client list, the server list, or none. */
export type Side = 'client' | 'server';

const header =
  '// Generated by `nx sync` from the packages that have `runtime/client.ts` or `runtime/server.server.ts`. Do not edit it.';

/** The side of an app, by the app rules of tools/apps.ts: a server app, a client app, or neither. */
export function sideOf(manifest: Manifest): Side | null {
  if (isServerApp(manifest)) {
    return 'server';
  }
  return isClientApp(manifest) ? 'client' : null;
}

/** The text of the list file of one side, for the packages that name it, sorted by name. */
export function listOf(side: Side, packages: ReadonlyArray<string>): string {
  const suffix = side === 'client' ? 'Client' : 'Server';
  const file = side === 'client' ? 'client' : 'server.server';
  const entries = packages.map((name) => ({
    variable: `${names(name).propertyName}${suffix}`,
    module: `@repo/${name}/runtime/${file}`,
  }));
  const imports = entries.map((entry) => `import { ${entry.variable} } from '${entry.module}';`);
  const variables = entries.map((entry) => entry.variable);
  const single = `export const packages = [${variables.join(', ')}];`;
  const body =
    single.length <= 100
      ? single
      : ['export const packages = [', ...variables.map((name) => `  ${name},`), '];'].join('\n');
  const head = imports.length ? [...imports, ''] : [];
  return [header, ...head, body, ''].join('\n');
}

/**
 * The packages with the runtime file of one side, sorted by name. The sync
 * engine has a `runtime/server.server.ts` of its own, but it holds no contract,
 * so it is not a package of the list.
 */
function packagesWith(tree: Tree, file: string): Array<string> {
  return tree
    .children('packages')
    .filter((name) => name !== 'sync' && tree.exists(`packages/${name}/${file}`))
    .toSorted();
}

/**
 * Writes the list of each app that has a side. A client app keeps its code in
 * `lib/` when it has one, and in `src/` otherwise. An app with no side, such as
 * the command-line app, gets no list. Returns the lists that changed.
 */
export function writeLists(tree: Tree): Array<string> {
  const changed: Array<string> = [];
  for (const app of tree.children('apps')) {
    const manifest = `apps/${app}/package.json`;
    if (!tree.exists(manifest)) {
      continue;
    }
    const side = sideOf(readJson<Manifest>(tree, manifest));
    if (!side) {
      continue;
    }
    const folder = tree.children(`apps/${app}/lib`).length ? 'lib' : 'src';
    const target = `apps/${app}/${folder}/packages.ts`;
    const packages = packagesWith(
      tree,
      side === 'client' ? 'runtime/client.ts' : 'runtime/server.server.ts',
    );
    const content = listOf(side, packages);
    if (tree.read(target, 'utf-8') !== content) {
      tree.write(target, content);
      changed.push(target);
    }
  }
  return changed;
}

/** The sync generator: writes the app lists, and reports each one that was out of date. */
export function packagesGenerator(tree: Tree): { readonly outOfSyncMessage?: string } {
  const changed = writeLists(tree);
  return changed.length
    ? {
        outOfSyncMessage: `The app lists are out of date: ${changed.join(', ')}. Run \`nx sync\`.`,
      }
    : {};
}
