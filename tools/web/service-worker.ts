import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { firstScreen } from '@tools/check-bundle';

/**
 * The build step after the web build of a client app: `bun
 * tools/web/service-worker.ts <built client folder>`. It writes `sw.js`, a
 * service worker that precaches every file of the build, so a warm visit
 * loads nothing from the network. It also writes the sync chunks into the
 * boot script of each page, so a warm visit can preload them from the cache.
 * It reads the files of the folder and the manifest of Vite, so it works for
 * a One build and for a plain Vite build. See docs/principles/fast-first-load.md.
 */

export type Manifest = Record<
  string,
  {
    readonly file: string;
    readonly isDynamicEntry?: boolean;
    readonly imports?: ReadonlyArray<string>;
  }
>;

/** The marker in the boot script that the build replaces with the sync chunks. */
export const syncChunksMarker = 'const syncChunks = [];';

/** Each file of a built client folder, as a path from it. A folder that starts with a dot holds build data, not a file to serve. */
export function builtFiles(dist: string, folder = ''): Array<string> {
  return readdirSync(path.join(dist, folder), { withFileTypes: true }).flatMap((entry) => {
    const name = path.posix.join(folder, entry.name);
    if (entry.isDirectory()) {
      return entry.name.startsWith('.') ? [] : builtFiles(dist, name);
    }
    return name === 'sw.js' ? [] : [name];
  });
}

/** Every URL of the build: each page, chunk, style sheet and asset, and `/` for the home page. */
export function precacheList(files: ReadonlyArray<string>): Array<string> {
  const urls = files.map((file) => `/${file}`);
  return [...new Set(urls.includes('/index.html') ? ['/', ...urls] : urls)].toSorted();
}

/**
 * The chunks of the sync transport: the dynamic entry of
 * `packages/sync/runtime/transport.ts` and each chunk it imports, without the
 * chunks that the first screen of the page already loads.
 */
export function syncChunks(manifest: Manifest, html: string): Array<string> {
  const first = new Set(firstScreen(html, manifest));
  const found = new Set<string>();
  const visit = (key: string) => {
    const chunk = manifest[key];
    if (!chunk || found.has(chunk.file)) {
      return;
    }
    found.add(chunk.file);
    for (const next of chunk.imports ?? []) {
      visit(next);
    }
  };
  for (const [key, chunk] of Object.entries(manifest)) {
    if (chunk.isDynamicEntry && key.endsWith('packages/sync/runtime/transport.ts')) {
      visit(key);
    }
  }
  return [...found]
    .filter((file) => !first.has(file))
    .map((file) => `/${file}`)
    .toSorted();
}

/**
 * The cached page of a navigation: `/notes.html` for `/notes`, and the home
 * page when the path has no page. The worker runs the source of this function.
 */
export function pageFor(urls: ReadonlyArray<string>, pathname: string): string {
  const base = pathname.replace(/\/$/u, '');
  return (
    [`${base}.html`, `${base}/index.html`].find((page) => urls.includes(page)) ?? '/index.html'
  );
}

/**
 * The service worker. It caches the build on install and deletes the caches of
 * older builds on activate. A request for a build file gets the cached copy
 * first. A navigation gets the cached page of its path, such as `/notes.html`
 * for `/notes`, or the home page when the path has no page. Every other
 * request, such as the sync socket, goes to the network.
 */
export function serviceWorkerSource(urls: ReadonlyArray<string>): string {
  const version = Bun.hash(urls.join('\n')).toString(36);
  return `// Generated by tools/web/service-worker.ts. Do not edit.
const cacheName = 'build-${version}';
const urls = ${JSON.stringify(urls)};
const pageFor = ${pageFor.toString()};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(cacheName).then((cache) => cache.addAll(urls)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((name) => name.startsWith('build-') && name !== cacheName).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== location.origin) return;
  const key = event.request.mode === 'navigate' ? pageFor(urls, url.pathname) : url.pathname;
  if (!urls.includes(key)) return;
  event.respondWith(caches.match(key).then((cached) => cached ?? fetch(event.request)));
});
`;
}

/** The HTML with the sync chunks in the boot script, so a warm visit can preload them. */
export function withSyncChunks(html: string, chunks: ReadonlyArray<string>): string {
  if (!html.includes(syncChunksMarker)) {
    throw new Error(
      `A page has no \`${syncChunksMarker}\` in its boot script. Restore it from the template.`,
    );
  }
  return html.replace(syncChunksMarker, `const syncChunks = ${JSON.stringify(chunks)};`);
}

if (import.meta.main) {
  const dist = path.resolve(process.argv[2] ?? 'dist');
  const manifest: Manifest = JSON.parse(
    readFileSync(path.join(dist, '.vite/manifest.json'), 'utf-8'),
  );
  const files = builtFiles(dist);
  const pages = files.filter((file) => file.endsWith('.html'));
  for (const page of pages) {
    const file = path.join(dist, page);
    const html = readFileSync(file, 'utf-8');
    writeFileSync(file, withSyncChunks(html, syncChunks(manifest, html)));
  }
  // The pages changed, and the worker names its cache by the list alone, so the list is read first.
  writeFileSync(path.join(dist, 'sw.js'), serviceWorkerSource(precacheList(files)));
  console.log(`Wrote ${path.join(dist, 'sw.js')} and the sync chunks in ${pages.length} pages.`);
}
