import path from 'node:path';

import { firstScreen } from '@tools/check-bundle';

/**
 * The build step after `vite build` in `apps/web`. It writes `sw.js`, a
 * service worker that precaches every file of the build, so a warm visit
 * loads nothing from the network. It also writes the sync chunks into the
 * boot script of `index.html`, so a warm visit can preload them from the
 * cache. See docs/principles/fast-first-load.md.
 */

export type Manifest = Record<
  string,
  {
    readonly file: string;
    readonly src?: string;
    readonly isEntry?: boolean;
    readonly isDynamicEntry?: boolean;
    readonly imports?: ReadonlyArray<string>;
    readonly dynamicImports?: ReadonlyArray<string>;
    readonly css?: ReadonlyArray<string>;
    readonly assets?: ReadonlyArray<string>;
  }
>;

/** The marker in the boot script that the build replaces with the sync chunks. */
export const syncChunksMarker = 'const syncChunks = [];';

/** Every URL of the build: the HTML, each chunk, each style sheet and each asset. */
export function precacheList(manifest: Manifest): Array<string> {
  const files = Object.values(manifest).flatMap((chunk) => [
    chunk.file,
    ...(chunk.css ?? []),
    ...(chunk.assets ?? []),
  ]);
  return ['/', '/index.html', ...new Set(files.map((file) => `/${file}`))].toSorted();
}

/**
 * The chunks of the sync transport: the dynamic entry of
 * `packages/sync/runtime/transport.ts` and each chunk it imports, without the
 * chunks that the first screen already loads.
 */
export function syncChunks(manifest: Manifest): Array<string> {
  const first = new Set(firstScreen(manifest));
  const found = new Set<string>();
  const visit = (key: string) => {
    const chunk = manifest[key];
    if (!chunk || found.has(chunk.file)) {
      return;
    }
    found.add(chunk.file);
    for (const next of chunk.imports ?? []) {
      visit(next);
    }
  };
  for (const [key, chunk] of Object.entries(manifest)) {
    if (chunk.isDynamicEntry && key.endsWith('packages/sync/runtime/transport.ts')) {
      visit(key);
    }
  }
  return [...found]
    .filter((file) => !first.has(file))
    .map((file) => `/${file}`)
    .toSorted();
}

/**
 * The service worker. It caches the build on install and deletes the caches of
 * older builds on activate. A request for a build file or a page gets the
 * cached copy first. Every other request, such as the sync socket, goes to the
 * network.
 */
export function serviceWorkerSource(urls: ReadonlyArray<string>): string {
  const version = Bun.hash(urls.join('\n')).toString(36);
  return `// Generated by tools/web/service-worker.ts. Do not edit.
const cacheName = 'build-${version}';
const urls = ${JSON.stringify(urls)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(cacheName).then((cache) => cache.addAll(urls)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((name) => name.startsWith('build-') && name !== cacheName).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== location.origin) return;
  const key = event.request.mode === 'navigate' ? '/index.html' : url.pathname;
  if (!urls.includes(key)) return;
  event.respondWith(caches.match(key).then((cached) => cached ?? fetch(event.request)));
});
`;
}

/** The HTML with the sync chunks in the boot script, so a warm visit can preload them. */
export function withSyncChunks(html: string, chunks: ReadonlyArray<string>): string {
  if (!html.includes(syncChunksMarker)) {
    throw new Error(
      `index.html has no \`${syncChunksMarker}\` in its boot script. Restore it from the template.`,
    );
  }
  return html.replace(syncChunksMarker, `const syncChunks = ${JSON.stringify(chunks)};`);
}

if (import.meta.main) {
  const dist = path.resolve(process.argv[2] ?? 'dist');
  const manifest: Manifest = await Bun.file(path.join(dist, '.vite/manifest.json')).json();
  const html = path.join(dist, 'index.html');
  await Bun.write(path.join(dist, 'sw.js'), serviceWorkerSource(precacheList(manifest)));
  await Bun.write(html, withSyncChunks(await Bun.file(html).text(), syncChunks(manifest)));
  console.log(`Wrote ${path.join(dist, 'sw.js')} and the sync chunks in index.html.`);
}
