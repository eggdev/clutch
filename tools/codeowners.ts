import { existsSync, readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { guardrailPatterns } from '@tools/agent-hooks/guard-guardrails';
import { parse } from 'yaml';

/**
 * Generates .github/CODEOWNERS from the `one-way-door` tier of
 * .clutch/risk.yaml, so the paths that need a person's review are listed in
 * one place. The main ruleset requires a code owner's approval, so GitHub
 * asks the owner to approve each one-way-door PR, and no other. The owner
 * comes from the current file, which kickoff sets. check-agent-hooks fails
 * when the file drifts. See .agents/skills/deliver/references/pull-requests.md#approval.
 */
export const codeownersFile = '.github/CODEOWNERS';
const riskFile = '.clutch/risk.yaml';

type Rule = { tier: string; paths?: Array<string>; guardrails?: string; except?: Array<string> };

/** `{a,b}/x` becomes `a/x` and `b/x`. CODEOWNERS has no braces. */
function expandBraces(glob: string): Array<string> {
  const match = /\{([^{}]*)\}/u.exec(glob);
  if (!match) {
    return [glob];
  }
  return match[1]
    .split(',')
    .flatMap((part) =>
      expandBraces(glob.slice(0, match.index) + part + glob.slice(match.index + match[0].length)),
    );
}

/**
 * The CODEOWNERS patterns for a risk glob: `tools/lint/**` becomes
 * `/tools/lint/`, a glob from the root gets a leading `/`, and `**\/x` stays,
 * so it matches anywhere.
 */
export function ownerPatterns(glob: string) {
  return expandBraces(glob).map((one) => {
    const trimmed = one.endsWith('/**') ? one.slice(0, -2) : one;
    return trimmed.startsWith('**/') ? trimmed : `/${trimmed}`;
  });
}

/** Each glob of the one-way-door tier, in file order. Without risk.yaml, the guardrail list. */
export function oneWayDoorGlobs(root: string) {
  const file = path.join(root, riskFile);
  if (!existsSync(file)) {
    return guardrailPatterns(root);
  }
  const rules = (
    (parse(readFileSync(file, 'utf-8')) as { rules?: Array<Rule> }).rules ?? []
  ).filter((rule) => rule.tier === 'one-way-door');
  return rules.flatMap((rule) => {
    if (rule.except?.length) {
      throw new Error(
        `${riskFile}: a one-way-door rule has \`except\`, which CODEOWNERS cannot express. Narrow its paths instead.`,
      );
    }
    const listed = rule.guardrails
      ? (
          JSON.parse(readFileSync(path.join(root, rule.guardrails), 'utf-8')) as {
            patterns: Array<string>;
          }
        ).patterns
      : [];
    return [...listed, ...(rule.paths ?? [])];
  });
}

/** The owners on the first rule line of the current file, such as `@eggdev`. */
export function currentOwners(text: string) {
  const line = text
    .split('\n')
    .map((item) => item.trim())
    .find((item) => item && !item.startsWith('#'));
  return line?.split(/\s+/u).slice(1) ?? [];
}

const header = `# Generated by tools/codeowners.ts from the one-way-door tier of
# .clutch/risk.yaml. Do not edit it by hand: change risk.yaml, then run
#   mise exec -- bun tools/codeowners.ts --write
# The main ruleset requires a code owner's approval, so each pull request that
# changes one of these paths waits for the owner, and every other pull request
# stays delegated. check-agent-hooks fails when this file drifts. Kickoff
# replaces @eggdev with the owner of the project.
#
# Escape hatches live in these files. A reviewer checks each one against the
# table in docs/contributing/harness-engineering.md#guardrail-files.
`;

/** The whole CODEOWNERS text for these globs and owners. */
export function codeownersText(globs: Array<string>, owners: Array<string>) {
  const patterns = [...new Set(globs.flatMap(ownerPatterns))];
  return `${header}\n${patterns.map((pattern) => `${pattern} ${owners.join(' ')}`).join('\n')}\n`;
}

/** The file that the current risk.yaml and owners call for, or the reason there is none. */
export function expectedCodeowners(root: string): { problem: string } | { text: string } {
  const file = path.join(root, codeownersFile);
  const owners = existsSync(file) ? currentOwners(readFileSync(file, 'utf-8')) : [];
  if (owners.length === 0) {
    return {
      problem: `${codeownersFile} names no owner. Add a line such as \`/AGENTS.md @owner\`.`,
    };
  }
  return { text: codeownersText(oneWayDoorGlobs(root), owners) };
}

if (import.meta.main) {
  const { values } = parseArgs({ options: { write: { type: 'boolean' } } });
  const root = process.cwd();
  const expected = expectedCodeowners(root);
  if ('problem' in expected) {
    console.error(expected.problem);
    process.exitCode = 1;
  } else if (values.write) {
    await writeFile(path.join(root, codeownersFile), expected.text);
    console.log(`${codeownersFile} lists the one-way-door paths of ${riskFile}.`);
  } else {
    console.log(expected.text);
  }
}
