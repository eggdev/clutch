import { expect, test } from 'bun:test';

import type { Issue } from '@/issues/parse';
import { renderTracker } from '@/issues/render';

const issue = (id: string, fields: Partial<Issue> = {}): Issue => ({
  id,
  title: id,
  phase: 'P0',
  status: 'todo',
  dependsOn: [],
  pr: '',
  owner: 'agent',
  file: `.clutch/issues/${id}.md`,
  ...fields,
});

test('the tracker counts each phase and lists each issue in its phase', () => {
  const markdown = renderTracker([
    issue('CL-001', { status: 'done', pr: 'https://github.com/o/r/pull/1' }),
    issue('CL-002', { title: 'Use a | pipe', dependsOn: ['CL-001'] }),
    issue('CL-901', { phase: 'later', owner: 'brendan' }),
  ]);
  expect(markdown).toBe(
    [
      '# Clutch tracker',
      'Generated by `clutch issues --write`. Do not edit by hand.',
      [
        '| Phase | todo | in_progress | blocked | review | done | Total |',
        '| --- | --- | --- | --- | --- | --- | --- |',
        '| P0 | 1 | 0 | 0 | 0 | 1 | 2 |',
        '| later | 1 | 0 | 0 | 0 | 0 | 1 |',
        '| All | 2 | 0 | 0 | 0 | 1 | 3 |',
      ].join('\n'),
      [
        '## P0',
        '',
        '| ID | Title | Status | Depends on | PR | Owner |',
        '| --- | --- | --- | --- | --- | --- |',
        '| CL-001 | CL-001 | done | - | https://github.com/o/r/pull/1 | agent |',
        String.raw`| CL-002 | Use a \| pipe | todo | CL-001 |  | agent |`,
      ].join('\n'),
      [
        '## later',
        '',
        '| ID | Title | Status | Depends on | PR | Owner |',
        '| --- | --- | --- | --- | --- | --- |',
        '| CL-901 | CL-901 | todo | - |  | brendan |',
      ].join('\n'),
    ].join('\n\n'),
  );
});
