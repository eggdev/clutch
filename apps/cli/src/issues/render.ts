import { phases, statuses } from '@/issues/parse';
import type { Issue } from '@/issues/parse';

export const trackerFile = '.clutch/TRACKER.md';

function row(cells: Array<string | number>) {
  return `| ${cells.join(' | ')} |`;
}

function table(header: Array<string>, rows: Array<Array<string | number>>) {
  return [row(header), row(header.map(() => '---')), ...rows.map(row)].join('\n');
}

/** Escapes a value for one Markdown table cell. */
function cell(text: string) {
  return text.replaceAll('|', String.raw`\|`);
}

/** The number of issues in each status, then the total. */
function counts(list: Array<Issue>) {
  return [
    ...statuses.map((status) => list.filter((issue) => issue.status === status).length),
    list.length,
  ];
}

/**
 * The tracker as Markdown: a count of issues by phase and status, then one
 * table per phase. It is not formatted. `clutch issues --write` runs oxfmt on it.
 */
export function renderTracker(issues: Array<Issue>) {
  const used = phases.filter((phase) => issues.some((issue) => issue.phase === phase));
  const sections = used.map((phase) => {
    const rows = issues
      .filter((issue) => issue.phase === phase)
      .map((issue) => [
        issue.id,
        cell(issue.title),
        issue.status,
        issue.dependsOn.join(', ') || '-',
        issue.pr,
        issue.owner,
      ]);
    return `## ${phase}\n\n${table(['ID', 'Title', 'Status', 'Depends on', 'PR', 'Owner'], rows)}`;
  });
  const summary = table(
    ['Phase', ...statuses, 'Total'],
    [
      ...used.map((phase) => [phase, ...counts(issues.filter((issue) => issue.phase === phase))]),
      ['All', ...counts(issues)],
    ],
  );
  return [
    '# Clutch tracker',
    'Generated by `clutch issues --write`. Do not edit by hand.',
    summary,
    ...sections,
  ].join('\n\n');
}
